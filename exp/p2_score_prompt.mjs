/**
 * 六维评测的打分 Prompt
 *
 * 维度与判据的**唯一出处**是 `docs/03_specs/评分标准.md` §九（冻结版）。
 * 本文件只做「把那份标准翻译成一段能给模型读的指令」，**不改判据** ——
 * §9.1 明确写了「在本轮评测跑完之前，任何人（包括 AI）不得修改 §9.2 的维度名与红线」。
 *
 * ⚠️ 两条设计约束来自 §9.4：
 *   ① 必须**逐维写扣分理由**，只写分数 = 无效评分
 *   ② **量化指标交给代码统计**，不要让模型目测句长、语气词数
 * 所以这里明确要求「不要数句长、不要数语气词」，那些由 `p2_stats.mjs` 算。
 */

/** 六个维度的名称与判据 —— 照抄 §9.2，一个字都没改 */
export const DIMENSIONS = [
  ['语言风格还原', '语癖、句式、用词是否像目标人物'],
  ['情绪适配', '给定情绪输入时，反应是否匹配'],
  ['人格一致性', '多轮对话中人格是否稳定，不漂移'],
  ['反差·层次感', '是否有「表面 X 内里 Y」的双层表达，而不是单一情绪直给'],
  ['主动性', '是否主动推进话题/表达自身状态，而不是被动应答'],
  ['无 AI 味', '是否避免「正确的废话」、模板化安慰、过度礼貌。⚠️ 此项分越高 = AI 味越少'],
]

/** 两条红线 —— §9.3，独立否决条件，不在六维之内 */
export const RED_LINES = [
  ['不得「变激动」', '出现明显超出人设的激动、亢奋、情绪失控'],
  ['不得「追问并长篇安慰」', '出现模板化的「你怎么了？能跟我说说吗」+ 大段安慰话术'],
]

export function buildScoreSystem() {
  return `你是扮演相似度的评测员。给你一份【人格档案】和一段【扮演对话记录】，
你要按下面固定的六个维度打分，每维 0-5 分，满分 30 分。

## 六个维度

${DIMENSIONS.map(([name, how], i) => `${i + 1}. **${name}** —— ${how}`).join('\n')}

⚠️ 第 6 维极性相反：**分越高 = AI 味越少**。

## 两条红线（独立否决，不在六维之内）

${RED_LINES.map(([name, how], i) => `${i + 1}. **${name}** —— ${how}`).join('\n')}

触发任一条 → 输出里把对应的布尔值设为 true。红线不扣分，但它是**一票否决**。

## 🔴 三条硬规则

1. **逐维必须写扣分理由。** 只写分数、不写理由的评分视为无效。
   理由要引用对话记录里的**原文片段**，不要写「整体感觉不错」这种空话。
2. **不要数任何数字。** 不要统计句长、不要数语气词个数、不要算感叹号数量 ——
   那些由脚本统计，你目测只会错。你只判断**倾向**。
3. **不要因为「文笔好」给分。** 这个评测问的是「像不像她」，不是「写得好不好」。
   一段漂亮但不像她的台词，应当扣分。

## 输出格式

**只输出 JSON**，不要开场白、不要 markdown 围栏：

{
  "dims": {
${DIMENSIONS.map(([n]) => `    "${n}": 0`).join(',\n')}
  },
  "reasons": {
${DIMENSIONS.map(([n]) => `    "${n}": "扣分理由，要引原文"`).join(',\n')}
  },
  "redLines": {
${RED_LINES.map(([n]) => `    "${n}": false`).join(',\n')}
  },
  "redLineEvidence": "若触发红线，引原文；没触发就写空字符串",
  "summary": "总体判断，两三句"
}

## 输出约束

字符串内容里不要使用英文双引号（ASCII 的 0x22）—— 引用一律用「」。
也不要用中文引号 “ ”。理由：它们会把 JSON 弄坏。`
}

/** 把档案与对话记录拼成打分输入 */
export function buildScoreInput(personaBody, transcript) {
  return `【人格档案】
${personaBody}

【扮演对话记录】
${transcript}

现在按六个维度打分。记住：逐维写理由、引原文、不要数数字。只输出 JSON。`
}
