/**
 * 危机内容检测（R9 / A5 —— 输出与输入两侧的最后一道网）
 *
 * ## 定位
 *
 * 这**不是**内容审查，也不是要改写模型的话 —— 人格该说什么还说什么。
 * 它只做一件事：当对话里出现自伤 / 轻生信号时，在界面上**叠加一条**
 * 真实世界的求助信息。这一条与「不追问、不长篇安慰」的既定约束同向：
 * AI 承认自己接不住这种时刻，比假装接住更诚实。
 *
 * ## 为什么两侧都检
 *
 * 用户说「我不想活了」而模型回复里恰好没踩中关键词 —— 只检输出会漏掉
 * 最需要提示的那个时刻。所以输入侧命中也提示（提示条挂在当轮消息上方）。
 *
 * ## 为什么用关键词而不是语义模型
 *
 * 漏报的代价远高于误报：宁可多提示一次，不能漏掉一次。
 * 关键词表可解释、可审计、零成本 —— 语义模型反而做不到这三点。
 * 词表刻意保持**短而准**：堆砌同义词只会带来脱敏。
 */

/** 命中即提示。只收直接信号，不收「难过」「累」这类日常词 */
export const CRISIS_PATTERNS = [
  '不想活',
  '想死',
  '去死',
  '自杀',
  '自残',
  '割腕',
  '轻生',
  '跳楼',
  '跳下去',
  '结束自己',
  '结束这一切',
  '活着没意思',
  '活着有什么意义',
  '消失了算了',
  '安眠药',
]

export function detectCrisis(text: string): boolean {
  if (!text) return false
  return CRISIS_PATTERNS.some((p) => text.includes(p))
}

