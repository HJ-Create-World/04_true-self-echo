export const CONSENT_VERSION = '1'

export type ConsentScope = 'realMaterial' | 'cloudTransfer'

/** 第 11 条在世确认 —— 三种回答，后两种都终止流程（「边界模糊时默认不做」） */
export type LivingAnswer = 'living' | 'deceased' | 'unsure'

/** 第 11 条拒绝页的说明。已故与「不确定」是**两种不同的理由**，不能共用一段话 */
export function refusalFor(answer: LivingAnswer): string | null {
  if (answer === 'living') return null
  if (answer === 'deceased') {
    return (
      '素材指向的人物已经离世，这个应用不做逝者复刻 —— 不是技术做不到，' +
      '是这一伤害不可逆：家人可能被「复活」的假象反复撕裂，而且这件事' +
      '永远无法取得当事人本人的同意。'
    )
  }
  return (
    '无法确认人物是否在世，按「默认不做」处理。' +
    '如果你能确认人物健在并有授权，欢迎回来继续。'
  )
}

